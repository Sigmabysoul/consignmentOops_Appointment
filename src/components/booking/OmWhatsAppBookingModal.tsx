"use client";

import React, { useState, useEffect } from "react";
import {
  X,
  MessageSquare,
  Copy,
  Check,
  ExternalLink,
  Edit3,
  RotateCcw,
  Building,
  Calendar,
  Layers,
  Phone,
  DollarSign,
  Truck,
} from "lucide-react";
import { AppointmentOrder } from "@/lib/types";
import { useToast } from "@/components/ui/Toast";
import { ChannelBadge } from "@/components/ui/ChannelBadge";
import {
  OmWhatsAppConfig,
  DEFAULT_OM_WHATSAPP_CONFIG,
  buildOmWhatsAppDraft,
  getWhatsAppWebUrl,
  getWhatsAppUniversalUrl,
} from "@/lib/om-whatsapp-booking";
import { formatDateDisplay } from "@/lib/date-utils";

interface OmWhatsAppBookingModalProps {
  order: AppointmentOrder | null;
  isOpen: boolean;
  onClose: () => void;
  onOrderUpdated?: () => void;
}

export function OmWhatsAppBookingModal({
  order,
  isOpen,
  onClose,
  onOrderUpdated,
}: OmWhatsAppBookingModalProps) {
  const { showToast } = useToast();

  const [config, setConfig] = useState<OmWhatsAppConfig>(DEFAULT_OM_WHATSAPP_CONFIG);
  const [phoneNumber, setPhoneNumber] = useState<string>("9477070699");
  const [declaredValue, setDeclaredValue] = useState<string>("");
  const [isEditingDraft, setIsEditingDraft] = useState<boolean>(false);
  const [manualDraftText, setManualDraftText] = useState<string>("");
  const [copied, setCopied] = useState<boolean>(false);
  const [isUpdating, setIsUpdating] = useState<boolean>(false);

  // Load active presets on open
  useEffect(() => {
    if (!isOpen) return;

    fetch("/api/shipping-presets")
      .then((res) => res.json())
      .then((data) => {
        if (data.presets?.omWhatsAppConfig) {
          const cfg = data.presets.omWhatsAppConfig as OmWhatsAppConfig;
          setConfig(cfg);
          if (cfg.phoneNumber) {
            setPhoneNumber(cfg.phoneNumber);
          }
        }
      })
      .catch(() => {});
  }, [isOpen]);

  // Initialize order values when order changes
  useEffect(() => {
    if (!order) return;

    const initialVal =
      (order.customData as any)?.invoiceValue ||
      (order.customData as any)?.declaredValue ||
      "";
    setDeclaredValue(initialVal ? String(initialVal) : "");
    setIsEditingDraft(false);
    setManualDraftText("");
  }, [order]);

  if (!isOpen || !order) return null;

  // Auto-generate draft message from current order and value
  const autoGeneratedDraft = buildOmWhatsAppDraft(order, config, declaredValue);
  const finalDraftMessage = isEditingDraft ? manualDraftText : autoGeneratedDraft;

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(finalDraftMessage);
      setCopied(true);
      showToast("WhatsApp booking message copied to clipboard", "success");
      setTimeout(() => setCopied(false), 2000);
    } catch {
      showToast("Failed to copy message", "error");
    }
  };

  const handleSendWhatsApp = async () => {
    const trimmedValue = declaredValue.replace(/,/g, "").trim();
    if (trimmedValue && !/^\d+(\.\d+)?$/.test(trimmedValue)) {
      showToast("Order value must be a number (e.g. 77662 or 77662.50)", "error");
      return;
    }

    // Open the tab now, while we are still inside the click: a window.open() after an `await`
    // is treated as an unrequested popup and blocked. The tab is pointed at WhatsApp once saved.
    const waTab = window.open("", "_blank");
    setIsUpdating(true);
    try {
      // 1. Assign OM Logistics to the order and save the entered invoice value
      const res = await fetch(`/api/orders/${order.id}`, {
        method: "PATCH",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          courierPartner: "OM Logistics",
          invoiceValue: trimmedValue === "" ? null : Number(Number(trimmedValue).toFixed(2)),
        }),
      });

      if (!res.ok) {
        const data = await res.json().catch(() => ({}));
        throw new Error(data.error || "Failed to update order");
      }

      // 2. Open WhatsApp Web with the drafted message
      const webUrl = getWhatsAppWebUrl(phoneNumber, finalDraftMessage);
      if (waTab) {
        waTab.opener = null;
        waTab.location.href = webUrl;
        showToast(`OM Logistics assigned & WhatsApp Web opened for #${order.roPoNumber}`, "success");
      } else {
        // Popups blocked entirely: keep this app open and let the operator send it themselves.
        await navigator.clipboard.writeText(finalDraftMessage).catch(() => {});
        showToast(
          `OM Logistics assigned. Popup blocked: the message is copied, open WhatsApp and paste it.`,
          "info"
        );
      }

      onOrderUpdated?.();
      onClose();
    } catch (err: any) {
      waTab?.close();
      showToast(err.message || "Failed to assign OM Logistics", "error");
    } finally {
      setIsUpdating(false);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-5 overflow-y-auto">
      {/* Backdrop */}
      <div className="ui-overlay transition-opacity" onClick={onClose} />

      {/* Main Dialog Window */}
      <div className="ui-dialog max-w-2xl z-10 animate-scale-in">
        {/* ── Modal Header ── */}
        <div className="ui-dialog-header">
          <div className="flex items-center gap-3 min-w-0">
            <div className="w-9 h-9 shrink-0 rounded-lg bg-emerald-50 border border-emerald-100 flex items-center justify-center">
              <MessageSquare className="w-5 h-5 text-emerald-600" />
            </div>
            <div className="min-w-0">
              <div className="flex flex-wrap items-center gap-2">
                <h3 className="text-base font-semibold text-slate-900">OM Logistics pickup booking</h3>
                <ChannelBadge channel={order.channel} size="sm" />
              </div>
              <div className="ui-muted mt-0.5 flex flex-wrap items-center gap-x-2">
                <span>
                  RO/PO <span className="ui-mono font-medium text-slate-700">{order.roPoNumber}</span>
                </span>
                <span className="text-slate-300">·</span>
                <span>
                  Pickup <span className="font-medium text-slate-700">{order.pickupDate ? formatDateDisplay(order.pickupDate) : "Today"}</span>
                </span>
                <span className="text-slate-300">·</span>
                <span>Sent over WhatsApp</span>
              </div>
            </div>
          </div>

          <button type="button" onClick={onClose} className="ui-icon-btn shrink-0" title="Close">
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* ── Modal Body ── */}
        <div className="flex-1 overflow-y-auto bg-slate-50/60 p-4 sm:p-5 space-y-4">
          {/* Value and WhatsApp number */}
          <div className="ui-card ui-card-body grid grid-cols-1 sm:grid-cols-2 gap-4">
            {/* Shipment Value Input */}
            <div>
              <label className="ui-label flex items-center justify-between">
                <span className="flex items-center gap-1">
                  <DollarSign className="w-3.5 h-3.5 text-slate-400" />
                  Shipment value (₹)
                </span>
                <span className="rounded-full border border-amber-200 bg-amber-50 px-1.5 text-[10px] font-medium text-amber-700">
                  Required
                </span>
              </label>
              <input
                type="number"
                step="0.01"
                placeholder="e.g. 77662.00"
                value={declaredValue}
                onChange={(e) => setDeclaredValue(e.target.value)}
                autoFocus
                className="ui-input tabular-nums font-medium"
              />
              <span className="ui-muted mt-1 block">Updates the Value row in the WhatsApp draft.</span>
            </div>

            {/* OM Logistics Phone Number */}
            <div>
              <label className="ui-label flex items-center justify-between">
                <span className="flex items-center gap-1">
                  <Phone className="w-3.5 h-3.5 text-slate-400" />
                  OM Logistics WhatsApp number
                </span>
                <span className="text-[10px] font-normal text-slate-400">Editable</span>
              </label>
              <input
                type="text"
                value={phoneNumber}
                onChange={(e) => setPhoneNumber(e.target.value)}
                placeholder="e.g. 9477070699"
                className="ui-input ui-mono font-medium"
              />
              <span className="ui-muted mt-1 block">
                Tested with {phoneNumber || "9477070699"}. Country code +91 is added automatically.
              </span>
            </div>
          </div>

          {/* WhatsApp Message Preview Box */}
          <section className="ui-card">
            <div className="ui-card-header">
              <span className="ui-card-title">
                Message preview
                <span className="ui-chip">WhatsApp format</span>
              </span>

              <div className="flex items-center gap-1">
                <button
                  type="button"
                  onClick={() => {
                    if (!isEditingDraft) {
                      setManualDraftText(autoGeneratedDraft);
                      setIsEditingDraft(true);
                    } else {
                      setIsEditingDraft(false);
                    }
                  }}
                  className="ui-btn-ghost ui-btn-sm"
                >
                  <Edit3 className="w-3 h-3" />
                  <span>{isEditingDraft ? "Auto format" : "Edit text"}</span>
                </button>

                <button
                  type="button"
                  onClick={handleCopy}
                  className="ui-btn-ghost ui-btn-sm"
                  title="Copy message to clipboard"
                >
                  {copied ? (
                    <>
                      <Check className="w-3 h-3 text-emerald-600" />
                      <span className="text-emerald-700">Copied</span>
                    </>
                  ) : (
                    <>
                      <Copy className="w-3 h-3" />
                      <span>Copy</span>
                    </>
                  )}
                </button>
              </div>
            </div>

            {/* Chat bubble preview */}
            <div className="p-3 sm:p-4 bg-[#efeae2] rounded-b-xl">
              <div className="rounded-lg bg-white p-3.5 text-xs leading-relaxed text-slate-800 shadow-sm">
                {isEditingDraft ? (
                  <textarea
                    rows={11}
                    value={manualDraftText}
                    onChange={(e) => setManualDraftText(e.target.value)}
                    className="ui-input font-mono text-xs"
                  />
                ) : (
                  <pre className="whitespace-pre-wrap font-sans text-xs text-slate-800 leading-relaxed select-text">
                    {autoGeneratedDraft}
                  </pre>
                )}
              </div>
            </div>
          </section>
        </div>

        {/* ── Modal Footer ── */}
        <div className="ui-dialog-footer flex-wrap">
          <div className="ui-muted">Opens WhatsApp Web with this message filled in and assigns OM Logistics.</div>

          <div className="flex items-center gap-2">
            <button type="button" onClick={onClose} className="ui-btn-ghost">
              Cancel
            </button>

            <button type="button" onClick={handleCopy} className="ui-btn-secondary">
              <Copy className="w-3.5 h-3.5 text-slate-500" />
              <span>Copy text</span>
            </button>

            <button
              type="button"
              disabled={isUpdating}
              onClick={handleSendWhatsApp}
              className="ui-btn-success"
            >
              {isUpdating ? (
                <span className="w-3.5 h-3.5 border-2 border-white border-t-transparent rounded-full animate-spin" />
              ) : (
                <MessageSquare className="w-3.5 h-3.5" />
              )}
              <span>Open in WhatsApp Web</span>
              <ExternalLink className="w-3.5 h-3.5 opacity-80" />
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
